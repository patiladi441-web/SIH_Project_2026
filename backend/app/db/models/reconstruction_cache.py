"""
app/db/models/reconstruction_cache.py
───────────────────────────────────────
Persisted cache of AI reconstruction results.

When a `/reconstruct` query misses Redis (or after TTL expiry), the result
is also stored here so it survives Redis eviction and container restarts.
"""

from __future__ import annotations

from datetime import date, datetime

from sqlalchemy import ARRAY, Boolean, Date, DateTime, Float, ForeignKey, Integer, String, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base


class ReconstructionCache(Base):
    __tablename__ = "reconstruction_cache"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)

    # Query key
    lat: Mapped[float] = mapped_column(Float, nullable=False, index=True)
    lon: Mapped[float] = mapped_column(Float, nullable=False, index=True)
    query_date: Mapped[date] = mapped_column(Date, nullable=False, index=True)

    # Reconstruction result — parallel arrays
    depths_m: Mapped[list[float]] = mapped_column(ARRAY(Float), nullable=False)
    temperature_c: Mapped[list[float]] = mapped_column(ARRAY(Float), nullable=False)
    confidence: Mapped[list[float] | None] = mapped_column(ARRAY(Float), nullable=True)

    # Reference to nearest Argo profile used for comparison
    nearest_argo_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("argo_profiles.id", ondelete="SET NULL"), nullable=True
    )

    # Whether this result was generated by mock AI or real model
    is_mock: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)

    # Cache-aside key (Redis key for this record)
    cache_key: Mapped[str] = mapped_column(String(64), nullable=False, index=True, unique=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    def __repr__(self) -> str:
        return (
            f"<ReconstructionCache id={self.id} "
            f"lat={self.lat} lon={self.lon} date={self.query_date} "
            f"mock={self.is_mock}>"
        )
